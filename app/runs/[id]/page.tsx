import Link from "next/link";
import { notFound, redirect } from "next/navigation";

import { RunReview } from "@/app/components/feedback/run-review";
import { PageHeader } from "@/app/components/page-header";
import { currentUser } from "@/app/server/auth/session";
import { getDatabase } from "@/app/server/db/database";
import { loadSnapshot } from "@/app/server/db/runs-repository";

export default async function RunPage({ params }: PageProps<"/runs/[id]">) {
  const { id } = await params;
  const user = await currentUser();
  if (!user) redirect(`/login?next=/runs/${encodeURIComponent(id)}`);

  const snapshot = loadSnapshot(getDatabase(), id, user.id);
  if (!snapshot) notFound();

  return (
    <div>
      <Link
        href="/runs"
        className="text-sm font-medium text-blue-700 hover:text-blue-900"
      >
        ← My runs
      </Link>
      <div className="mt-6">
        <PageHeader
          eyebrow={
            snapshot.run.mode === "rag" ? "Your question" : "Ontology run"
          }
          title={
            snapshot.run.mode === "rag"
              ? "Review the answer"
              : "Review the proposed matches"
          }
        >
          <p className="text-sm">
            {snapshot.run.documents.join(", ")} · generated by{" "}
            {snapshot.run.generationModel}, reranked by{" "}
            {snapshot.run.rerankingModel}
          </p>
          <p className="mt-2 text-sm">
            Accept or reject every answer, and add a comment when something is
            wrong. Mark chunks the model saw as relevant or irrelevant, and open
            &ldquo;Not sent to the model&rdquo; to flag chunks it should have
            used.
          </p>
        </PageHeader>
      </div>
      <RunReview snapshot={snapshot} />
    </div>
  );
}
